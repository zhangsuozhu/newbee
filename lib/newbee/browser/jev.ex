defmodule Newbee.Browser.Jev do
  @moduledoc """
  Jev-selected browser actions executed through the existing Playwright tool.

  The controller sends a bounded page snapshot and a code-owned action list to
  TypeSafe. Jev returns one action id; only the matching action generated by this
  module is passed to `Newbee.Tools.Browser`. It never returns or executes raw
  selectors, JavaScript, shell commands, or arbitrary URLs.

  ## Configuration

  Add a `typesafe` provider to `model.json` or `model.local.json`:

      {
        "providers": {
          "typesafe": {
            "baseUrl": "https://api.typesafe.ai",
            "apiKey": "${TYPESAFE_API_KEY}",
            "models": ["jev-latest"]
          }
        }
      }

  A literal `apiKey` is also accepted. `TYPESAFE_API_KEY` is used as a fallback
  when no provider is configured. Missing configuration is a recoverable error
  and does not change the regular Browser or LLM paths.
  """

  alias Newbee.Tools.Browser

  @default_base_url "https://api.typesafe.ai"
  @default_model "jev-latest"
  @default_max_steps 8
  @max_steps 32
  @default_min_confidence 0.60
  @max_candidates 32
  @browser_request_keys ~w(action_timeout idle_timeout profile viewport storage_state save_storage record_video_dir video_size)

  @doc "Run a bounded Jev-selected Playwright browser loop."
  def run(request, opts \\ [])

  def run(request, opts) when is_map(request) and is_list(opts) do
    with {:ok, request} <- normalize_request(request),
         {:ok, config} <- resolve_config(Keyword.get(opts, :config)),
         {:ok, session, snapshot} <- open_browser(request, opts) do
      result = run_loop(request, config, session, snapshot, opts, 0, [])
      finish(request, session, result, opts)
    end
  end

  def run(_, _), do: {:error, %{reason: :invalid_request, hint: "Jev browser request must be a map"}}

  defp normalize_request(request) do
    request = stringify_keys(request)
    goal = request["goal"]
    session = Map.get(request, "session", "new")

    cond do
      not is_binary(goal) or String.trim(goal) == "" ->
        {:error, %{reason: :invalid_goal, hint: "goal must be a non-empty string"}}

      not is_binary(session) or session == "" ->
        {:error, %{reason: :invalid_session, hint: "session must be \"new\" or an existing browser handle"}}

      session == "new" and not valid_url?(request["url"]) ->
        {:error, %{reason: :invalid_url, hint: "url is required when opening a new Jev browser session"}}

      session != "new" and Map.has_key?(request, "url") ->
        {:error, %{reason: :invalid_request, hint: "url cannot be changed on an existing browser session"}}

      true ->
        with {:ok, max_steps} <- bounded_integer(request["max_steps"], @default_max_steps, 1, @max_steps, :max_steps),
             {:ok, min_confidence} <-
               bounded_number(request["min_confidence"], @default_min_confidence, 0.0, 1.0, :min_confidence),
             {:ok, max_chars} <- bounded_integer(request["snapshot_max_chars"], 6_000, 256, 16_000, :snapshot_max_chars),
             {:ok, limit} <- bounded_integer(request["snapshot_limit"], 40, 1, 100, :snapshot_limit) do
          inputs = request["input_values"] || %{}
          allowed_hosts = request["allowed_hosts"] || []

          if is_map(inputs) and is_list(allowed_hosts) do
            {:ok,
             request
             |> Map.put("session", session)
             |> Map.put("max_steps", max_steps)
             |> Map.put("min_confidence", min_confidence)
             |> Map.put("snapshot_max_chars", max_chars)
             |> Map.put("snapshot_limit", limit)
             |> Map.put("input_values", inputs)
             |> Map.put("allowed_hosts", allowed_hosts)
             |> Map.put_new("allow_side_effects", false)
             |> Map.put_new("allow_navigation", true)
             |> Map.put_new("close", session == "new")}
          else
            {:error, %{reason: :invalid_request, hint: "input_values must be a map and allowed_hosts must be a list"}}
          end
        end
    end
  end

  defp open_browser(request, opts) do
    browser_run = browser_runner(opts)
    browser_request = browser_request(request, [snapshot_action(request)])

    case browser_run.(browser_request) do
      {:ok, result} ->
        with session when is_binary(session) <- result["session"] || request["session"],
             {:ok, snapshot} <- extract_snapshot(result) do
          {:ok, session, snapshot}
        else
          _ -> {:error, %{reason: :browser_snapshot_missing, hint: "Playwright did not return an initial snapshot"}}
        end

      {:error, reason} ->
        {:error, reason}
    end
  end

  defp run_loop(%{"max_steps" => max_steps} = request, _config, session, snapshot, _opts, step, history)
       when step >= max_steps do
    {:ok, result(request, session, "max_steps", snapshot, history)}
  end

  defp run_loop(request, config, session, snapshot, opts, step, history) do
    candidates = candidates(snapshot, request)
    min_confidence = request["min_confidence"]

    case choose(config, request, snapshot, candidates, history, opts) do
      {:ok, %{choice: "done", confidence: confidence, probabilities: probabilities}} ->
        {:ok,
         result(request, session, "done", snapshot, history, %{confidence: confidence, probabilities: probabilities})}

      {:ok, %{choice: "stop", confidence: confidence, probabilities: probabilities}} ->
        {:ok,
         result(request, session, "stopped", snapshot, history, %{
           reason: "jev_stop",
           confidence: confidence,
           probabilities: probabilities
         })}

      {:ok, %{choice: choice, confidence: confidence, probabilities: probabilities}} ->
        if confidence < min_confidence do
          {:ok,
           result(request, session, "stopped", snapshot, history, %{
             reason: "low_confidence",
             choice: choice,
             confidence: confidence,
             probabilities: probabilities
           })}
        else
          case Enum.find(candidates, &(&1.id == choice)) do
            nil ->
              {:error,
               %{reason: :jev_invalid_choice, hint: "Jev selected an action that was not offered", choice: choice}}

            candidate ->
              history =
                history ++
                  [
                    %{
                      "step" => step + 1,
                      "choice" => choice,
                      "confidence" => confidence,
                      "probabilities" => probabilities
                    }
                  ]

              with :ok <- execute_candidate(session, candidate, request, opts),
                   {:ok, next_snapshot} <- read_snapshot(session, request, opts) do
                run_loop(request, config, session, next_snapshot, opts, step + 1, history)
              else
                {:error, reason} -> {:error, Map.put(as_error(reason), :history, history)}
              end
          end
        end

      {:error, reason} ->
        {:error, reason}
    end
  end

  defp choose(config, request, snapshot, candidates, history, opts) do
    criteria = Map.new(candidates, fn candidate -> {candidate.id, candidate.description} end)

    state = %{
      "goal" => request["goal"],
      "page" => snapshot,
      "available_actions" =>
        Enum.map(candidates, fn candidate -> %{"id" => candidate.id, "description" => candidate.description} end),
      "previous_actions" => history
    }

    payload = %{
      "state" => state,
      "model" => config.model,
      "questions" => %{
        "action" => %{
          "type" => "choice",
          "instructions" =>
            "Choose exactly one available action to advance the goal. Use done only when the goal is already satisfied. Use stop when no safe action can make progress. Never invent an action id.",
          "criteria" => criteria
        }
      }
    }

    headers = [
      {"authorization", "Bearer " <> config.api_key},
      {"content-type", "application/json"},
      {"accept", "application/json"}
    ]

    case http_post(opts).(config.endpoint, payload, headers) do
      {:ok, %{status: status, body: body}} when status in 200..299 ->
        parse_choice(body, candidates)

      {:ok, %{status: status, body: body}} ->
        {:error, %{reason: :jev_http_error, status: status, detail: response_detail(body)}}

      {:error, reason} ->
        {:error, %{reason: :jev_transport_error, detail: reason}}
    end
  end

  defp parse_choice(body, candidates) when is_binary(body) do
    with {:ok, response} <- Jason.decode(body),
         answer when is_map(answer) <- get_in(response, ["answers", "action"]),
         choice when is_binary(choice) <- answer["choice"],
         confidence when is_number(confidence) and confidence >= 0 and confidence <= 1 <- answer["confidence"] do
      offered = MapSet.new(Enum.map(candidates, & &1.id))

      if MapSet.member?(offered, choice) do
        {:ok,
         %{
           choice: choice,
           confidence: confidence,
           probabilities: answer["probabilities"] || %{}
         }}
      else
        {:error, %{reason: :jev_invalid_choice, hint: "Jev selected an action that was not offered", choice: choice}}
      end
    else
      {:error, _} -> {:error, %{reason: :jev_invalid_response, hint: "Jev returned invalid JSON"}}
      nil -> {:error, %{reason: :jev_invalid_response, hint: "Jev response did not contain answers.action"}}
      _ -> {:error, %{reason: :jev_invalid_response, hint: "Jev action answer is missing choice or confidence"}}
    end
  end

  defp execute_candidate(session, candidate, request, opts) do
    browser_run = browser_runner(opts)
    browser_request = browser_request(request, [candidate.action], session)

    case browser_run.(browser_request) do
      {:ok, _result} -> :ok
      {:error, reason} -> {:error, reason}
    end
  end

  defp read_snapshot(session, request, opts) do
    browser_run = browser_runner(opts)

    case browser_run.(browser_request(request, [snapshot_action(request)], session)) do
      {:ok, result} -> extract_snapshot(result)
      {:error, reason} -> {:error, reason}
    end
  end

  defp finish(request, session, {:ok, value}, opts) do
    value = Map.put(value, "session", if(request["close"], do: nil, else: session))
    maybe_close(request, session, opts)
    {:ok, value}
  end

  defp finish(request, session, {:error, reason}, opts) do
    maybe_close(request, session, opts)
    {:error, reason}
  end

  defp maybe_close(%{"close" => false}, _session, _opts), do: :ok

  defp maybe_close(_request, session, opts) do
    _ = browser_runner(opts).(browser_request(%{"timeout" => 30_000}, [%{"action" => "close"}], session))
    :ok
  end

  defp result(request, session, status, snapshot, history, extra \\ %{}) do
    Map.merge(
      %{
        "status" => status,
        "goal" => request["goal"],
        "steps" => length(history),
        "snapshot" => snapshot,
        "decisions" => history,
        "session" => session
      },
      stringify_keys(extra)
    )
  end

  defp candidates(snapshot, request) do
    fixed = [
      candidate("done", "The goal is already satisfied; perform no browser action.", %{"action" => "wait", "ms" => 1}),
      candidate("stop", "Stop because the state is ambiguous or no safe action is available.", %{
        "action" => "wait",
        "ms" => 1
      }),
      candidate("scroll_down", "Scroll down to reveal more page content.", %{"action" => "scroll", "delta_y" => 600}),
      candidate("scroll_up", "Scroll up to reveal earlier page content.", %{"action" => "scroll", "delta_y" => -600})
    ]

    fixed =
      if request["allow_navigation"] == false do
        fixed
      else
        fixed ++
          [
            candidate("back", "Go back one page in browser history.", %{"action" => "back"}),
            candidate("forward", "Go forward one page in browser history.", %{"action" => "forward"})
          ]
      end

    controls = snapshot["controls"] || []
    links = snapshot["links"] || []

    control_candidates =
      controls
      |> Enum.with_index()
      |> Enum.flat_map(fn {control, index} -> control_candidate(control, index, request) end)

    link_candidates =
      links
      |> Enum.with_index()
      |> Enum.flat_map(fn {link, index} -> link_candidate(link, index, snapshot, request) end)

    (fixed ++ control_candidates ++ link_candidates)
    |> Enum.uniq_by(& &1.id)
    |> Enum.take(@max_candidates)
  end

  defp control_candidate(control, index, request) when is_map(control) do
    name = clean_text(control["name"])
    label = if name != "", do: name, else: clean_text(control["html_name"])
    tag = clean_text(control["tag"]) |> String.downcase()
    type = clean_text(control["type"]) |> String.downcase()
    role = clean_text(control["role"]) |> String.downcase()

    cond do
      control["disabled"] == true ->
        []

      label == "" ->
        []

      not request["allow_side_effects"] and dangerous_name?(label) ->
        []

      type in ["checkbox", "radio"] or role in ["checkbox", "radio", "switch"] ->
        [toggle_candidate(control, index, label)]

      tag == "select" or role == "combobox" ->
        select_candidate(control, index, label, request)

      tag in ["input", "textarea"] or role in ["textbox", "searchbox"] or control["contenteditable"] == true ->
        fill_candidate(control, index, label, request)

      true ->
        case locator_for(control) do
          nil ->
            []

          locator ->
            [
              candidate(
                "control_#{index}",
                "Click the control labelled #{clip(label, 160)}.",
                Map.merge(%{"action" => "click"}, locator)
              )
            ]
        end
    end
  end

  defp toggle_candidate(control, index, name) do
    action = if control["checked"] == true, do: "uncheck", else: "check"

    candidate(
      "control_#{index}",
      "#{String.capitalize(action)} the control labelled #{clip(name, 160)}.",
      Map.merge(%{"action" => action}, locator_for(control) || %{})
    )
  end

  defp select_candidate(control, index, name, request) do
    case input_value(control, request["input_values"]) do
      nil ->
        []

      value ->
        case locator_for(control) do
          nil ->
            []

          locator ->
            [
              candidate(
                "control_#{index}",
                "Select the supplied value for #{clip(name, 160)}.",
                Map.merge(%{"action" => "select", "value" => value}, locator)
              )
            ]
        end
    end
  end

  defp fill_candidate(control, index, name, request) do
    case input_value(control, request["input_values"]) do
      nil ->
        []

      value ->
        case locator_for(control) do
          nil ->
            []

          locator ->
            [
              candidate(
                "control_#{index}",
                "Fill #{clip(name, 160)} with the supplied value.",
                Map.merge(%{"action" => "fill", "value" => to_string(value)}, locator)
              )
            ]
        end
    end
  end

  defp link_candidate(link, index, snapshot, request) when is_map(link) do
    text = clean_text(link["text"])
    href = clean_text(link["href"])

    if text != "" and safe_link?(href, snapshot["url"], request) and
         (request["allow_side_effects"] or not dangerous_name?(text)) do
      [
        candidate("link_#{index}", "Open the link labelled #{clip(text, 160)}.", %{
          "action" => "click",
          "by" => "text",
          "selector" => text,
          "exact" => true
        })
      ]
    else
      []
    end
  end

  defp link_candidate(_, _, _, _), do: []

  defp locator_for(control) do
    id = clean_text(control["id"])
    name = clean_text(control["name"])
    html_name = clean_text(control["html_name"])
    tag = clean_text(control["tag"]) |> String.downcase()
    role = clean_text(control["role"]) |> String.downcase()
    role = if role == "", do: implicit_role(tag, control["type"]), else: role

    cond do
      id != "" -> %{"by" => "id", "selector" => id}
      role != "" and name != "" -> %{"by" => "role", "selector" => role, "name" => name, "exact" => true}
      tag in ["input", "textarea", "select"] and name != "" -> %{"by" => "label", "selector" => name, "exact" => true}
      name != "" -> %{"by" => "text", "selector" => name, "exact" => true}
      html_name != "" -> css_name_locator(tag, html_name)
      true -> nil
    end
  end

  # 无 id/可访问名时的兜底：用 HTML name 属性定位；值含换行/引号/反斜线则放弃。
  defp css_name_locator(tag, name) do
    if String.contains?(name, ["\n", "\r", "\"", "\\"]) do
      nil
    else
      prefix = if tag in ["input", "textarea", "select", "button"], do: tag, else: ""
      %{"by" => "css", "selector" => "#{prefix}[name=\"#{name}\"]"}
    end
  end

  defp implicit_role("button", _), do: "button"
  defp implicit_role("a", _), do: "link"
  defp implicit_role("select", _), do: "combobox"
  defp implicit_role("textarea", _), do: "textbox"
  defp implicit_role("input", type) when type in ["checkbox", "radio"], do: type
  defp implicit_role("input", "search"), do: "searchbox"
  defp implicit_role("input", _), do: "textbox"
  defp implicit_role(_, _), do: ""

  defp input_value(control, input_values) when is_map(input_values) do
    keys = [
      control["id"],
      control["html_name"],
      control["name"],
      control["label"],
      control["placeholder"],
      control["aria_label"]
    ]

    Enum.find_value(keys, fn key ->
      key = clean_text(key)
      if key != "" and Map.has_key?(input_values, key), do: input_values[key]
    end)
  end

  defp input_value(_, _), do: nil

  defp safe_link?(href, page_url, request) do
    case URI.parse(href) do
      %URI{scheme: scheme} when scheme in ["javascript", "data", "mailto", "tel"] ->
        false

      %URI{host: nil} ->
        true

      %URI{host: host} ->
        allowed = Enum.map(request["allowed_hosts"], &to_string/1)
        page_host = if is_binary(page_url), do: URI.parse(page_url).host, else: nil
        request["allow_external"] == true or host == page_host or host in allowed
    end
  end

  defp dangerous_name?(text) do
    Regex.match?(
      ~r/\b(delete|remove|buy|purchase|pay|submit|send|publish|confirm|checkout|logout|unsubscribe)\b/i,
      text
    )
  end

  defp candidate(id, description, action), do: %{id: id, description: description, action: action}

  defp snapshot_action(request),
    do: %{"action" => "snapshot", "max_chars" => request["snapshot_max_chars"], "limit" => request["snapshot_limit"]}

  defp browser_request(request, actions, session \\ nil) do
    base = request["browser"] || %{}
    base = Map.merge(base, Map.take(request, @browser_request_keys))
    base = Map.put(base, "backend", "playwright") |> Map.put("actions", actions)

    base =
      if is_binary(session), do: Map.put(base, "session", session), else: Map.put(base, "session", request["session"])

    if base["session"] == "new" do
      Map.put(base, "url", request["url"])
    else
      Map.delete(base, "url")
    end
  end

  defp extract_snapshot(%{"results" => results}) when is_list(results) do
    case List.last(results) do
      %{"result" => snapshot} when is_map(snapshot) -> {:ok, snapshot}
      _ -> {:error, %{reason: :browser_snapshot_missing, hint: "Playwright snapshot result is missing"}}
    end
  end

  defp extract_snapshot(%{"snapshot" => snapshot}) when is_map(snapshot), do: {:ok, snapshot}

  defp extract_snapshot(_),
    do: {:error, %{reason: :browser_snapshot_missing, hint: "Playwright snapshot result is missing"}}

  defp resolve_config(nil) do
    cfg = Newbee.LLM.Config.load()
    provider = get_in(cfg, ["providers", "typesafe"]) || get_in(cfg, ["providers", "jev"]) || %{}
    resolve_config(provider)
  end

  defp resolve_config(config) when is_map(config) do
    base_url = config["baseUrl"] || config[:base_url] || config[:baseUrl] || @default_base_url
    endpoint = config["endpoint"] || config[:endpoint] || systemone_endpoint(base_url)
    api_key = config["apiKey"] || config[:api_key] || config[:apiKey] || System.get_env("TYPESAFE_API_KEY")
    api_key = expand_key(api_key)
    models = config["models"] || config[:models] || []
    model = config["model"] || config[:model] || List.first(models) || @default_model

    cond do
      not is_binary(api_key) or String.trim(api_key) == "" ->
        {:error, %{reason: :jev_not_configured, hint: "configure providers.typesafe.apiKey or TYPESAFE_API_KEY"}}

      not is_binary(endpoint) or String.trim(endpoint) == "" ->
        {:error, %{reason: :jev_not_configured, hint: "configure providers.typesafe.baseUrl"}}

      true ->
        {:ok, %{endpoint: endpoint, api_key: api_key, model: to_string(model)}}
    end
  end

  defp resolve_config(_),
    do: {:error, %{reason: :jev_not_configured, hint: "TypeSafe provider configuration must be a map"}}

  defp systemone_endpoint(base_url) when is_binary(base_url) do
    base_url = String.trim_trailing(base_url, "/")

    cond do
      String.ends_with?(base_url, "/systemone") -> base_url
      String.ends_with?(base_url, "/v1") -> base_url <> "/systemone"
      true -> base_url <> "/v1/systemone"
    end
  end

  defp systemone_endpoint(_), do: @default_base_url <> "/v1/systemone"

  defp expand_key("${" <> rest) do
    env = rest |> String.trim_trailing("}") |> String.trim()
    System.get_env(env)
  end

  defp expand_key(value) when is_binary(value), do: String.trim(value)
  defp expand_key(_), do: nil

  defp http_post(opts), do: Keyword.get(opts, :http_post, &Newbee.Tools.Http.post/3)
  defp browser_runner(opts), do: Keyword.get(opts, :browser_run, &Browser.run/1)

  defp valid_url?(url) when is_binary(url) do
    case URI.parse(url) do
      %URI{scheme: scheme, host: host} when scheme in ["http", "https"] and is_binary(host) and host != "" -> true
      _ -> false
    end
  end

  defp valid_url?(_), do: false

  defp bounded_integer(nil, default, _min, _max, _field), do: {:ok, default}

  defp bounded_integer(value, _default, min, max, _field) when is_integer(value) and value >= min and value <= max,
    do: {:ok, value}

  defp bounded_integer(value, _default, min, max, field),
    do: {:error, %{reason: :invalid_request, hint: "#{field} must be an integer from #{min} to #{max}", value: value}}

  defp bounded_number(nil, default, _min, _max, _field), do: {:ok, default}

  defp bounded_number(value, _default, min, max, _field) when is_number(value) and value >= min and value <= max,
    do: {:ok, value}

  defp bounded_number(value, _default, min, max, field),
    do: {:error, %{reason: :invalid_request, hint: "#{field} must be a number from #{min} to #{max}", value: value}}

  defp stringify_keys(map) when is_map(map),
    do: Map.new(map, fn {key, value} -> {to_string(key), stringify_value(value)} end)

  defp stringify_value(value) when is_map(value), do: stringify_keys(value)
  defp stringify_value(value) when is_list(value), do: Enum.map(value, &stringify_value/1)
  defp stringify_value(value), do: value

  defp clean_text(value) when is_binary(value), do: String.trim(value)
  defp clean_text(_), do: ""

  defp clip(value, max) when is_binary(value), do: String.slice(value, 0, max)
  defp clip(value, max), do: value |> to_string() |> String.slice(0, max)

  defp response_detail(body) when is_binary(body) do
    case Jason.decode(body) do
      {:ok, %{"detail" => detail}} -> detail
      {:ok, %{"error" => error}} -> error
      _ -> "TypeSafe returned a non-success response"
    end
  end

  defp response_detail(_), do: "TypeSafe returned a non-success response"

  defp as_error(%{reason: _} = reason), do: reason
  defp as_error(reason), do: %{reason: :browser_error, detail: reason}
end
