defmodule Newbee.Tools.BrowserJev do
  @behaviour Newbee.Environment.PluginContract

  @moduledoc """
  Jev-selected browser actions via Playwright.

  Jev chooses only from actions generated by code; Playwright performs the
  selected click, fill, toggle, navigation, or scroll. Missing Jev configuration
  is recoverable and leaves the regular Browser tool unchanged.

  ## Inputs

  `input_values` maps controls to values; keys match a control's HTML `name`,
  accessible name (label), id, placeholder, or aria-label. Clicking controls with
  side-effect labels (submit, send, pay, ...) requires `allow_side_effects: true`.

  ## Runnable example
      Newbee.Tools.BrowserJev.run(%{
        url: "https://example.com",
        goal: "Open the documentation link",
        max_steps: 4
      })
  """

  @doc false
  def id, do: "tool.browser.jev"

  @doc false
  def version, do: "1.0.0"

  @doc false
  def dependencies, do: []

  @doc false
  def describe do
    %{
      kind: :tool,
      summary: "Jev-selected browser actions executed through Playwright",
      when_to_use: "When a browser goal needs bounded semantic action selection over a live Playwright snapshot",
      avoid_when:
        "For deterministic browser plans use Newbee.Tools.Browser; Jev cannot be configured or visual input is required",
      capabilities: [:browser, :net],
      effects: [:process, :external, :fs],
      state_policy: :ephemeral,
      error_contract: %{recoverable: :error_tuple, unexpected: :raise},
      api: [
        %{
          name: :run,
          arity: 1,
          returns: "{:ok, result} | {:error, reason}",
          errors:
            "Invalid goals, missing Jev configuration, low confidence, browser, and HTTP failures are recoverable values"
        }
      ],
      examples: [
        "Newbee.Tools.BrowserJev.run(%{url: \"https://example.com\", goal: \"Open the documentation link\"})"
      ]
    }
  end

  @doc "Run a bounded Jev-selected Playwright browser loop."
  def run(request) when is_map(request), do: Newbee.Browser.Jev.run(request)

  def run(_), do: {:error, %{reason: :invalid_request, hint: "Jev browser request must be a map"}}
end
